import AppKit

/// 一次复制中被保存下来的一种剪贴板格式。
struct ClipContent: Equatable, Sendable {
    let type: NSPasteboard.PasteboardType
    let data: Data
}

/// 一次复制的采集结果：合并了所有剪贴板项中受支持的格式。
struct CapturedClip: Equatable, Sendable {
    var contents: [ClipContent]
    var sourceBundleID: String?
}

extension NSPasteboard.PasteboardType {
    /// Folita 写回剪贴板时附加的标记，监听到它说明是自己写的，不应再次记录。
    static let folitaOrigin = NSPasteboard.PasteboardType("app.folita.origin")

    // 约定见 http://nspasteboard.org ：密码管理器等用这些类型声明内容不应被记录。
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    static let heic = NSPasteboard.PasteboardType("public.heic")
}

/// 采集规则：哪些复制需要跳过、保留哪些格式。只依赖值类型，便于直接测试。
enum ClipboardCapture {
    /// 只保存这些格式。白名单而不是黑名单：各应用会往剪贴板塞大量私有或易变的格式
    /// （WebKit/Chromium 元数据、整页 WebArchive 等），逐个排除不现实。
    static let supportedTypes: [NSPasteboard.PasteboardType] = [
        .fileURL, .string, .rtf, .html, .png, .tiff, .jpeg, .heic,
    ]

    static let imageTypes: Set<NSPasteboard.PasteboardType> = [.png, .tiff, .jpeg, .heic]

    /// 出现任一类型即整次复制不记录。
    static let skipMarkerTypes: Set<NSPasteboard.PasteboardType> = [
        .concealed, .transient, .autoGenerated, .folitaOrigin,
    ]

    /// 单次复制保存的数据总量上限，超出则不记录，避免大图撑满存储。
    static let maxClipBytes = 10 * 1024 * 1024

    /// 只看类型与来源应用就能决定跳过的情况，此时无需读取任何数据。
    static func shouldSkip(
        types: Set<NSPasteboard.PasteboardType>,
        sourceBundleID: String?,
        ignoredBundleIDs: Set<String>
    ) -> Bool {
        if !types.isDisjoint(with: skipMarkerTypes) { return true }
        if let sourceBundleID, ignoredBundleIDs.contains(sourceBundleID) { return true }
        return types.isDisjoint(with: supportedTypes)
    }

    /// 把各剪贴板项读出的格式合并成一次复制。
    /// 部分应用（BBEdit、Edge）一次复制会放两个剪贴板项，合并后同一类型只保留第一份；
    /// 文件例外：Finder 复制多个文件时每个文件各占一项，必须全部保留。
    static func makeClip(
        items: [[ClipContent]],
        sourceBundleID: String?
    ) -> CapturedClip? {
        var seen = Set<NSPasteboard.PasteboardType>()
        var contents: [ClipContent] = []
        for content in items.joined() where supportedTypes.contains(content.type) {
            if content.type == .fileURL {
                guard !contents.contains(content) else { continue }
            } else {
                guard !seen.contains(content.type) else { continue }
                seen.insert(content.type)
            }
            contents.append(content)
        }

        guard !contents.isEmpty, hasMeaningfulContent(contents) else { return nil }
        guard contents.reduce(0, { $0 + $1.data.count }) <= maxClipBytes else { return nil }
        return CapturedClip(contents: contents, sourceBundleID: sourceBundleID)
    }

    /// 只有空白纯文本的复制没有意义（例如部分应用清空剪贴板的方式）。
    private static func hasMeaningfulContent(_ contents: [ClipContent]) -> Bool {
        contents.contains { content in
            guard content.type == .string else { return !content.data.isEmpty }
            let text = String(decoding: content.data, as: UTF8.self)
            return !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        }
    }
}
