import AppKit
import Testing
@testable import Folita

struct ClipboardCaptureTests {
    private func text(_ string: String) -> ClipContent {
        ClipContent(type: .string, data: Data(string.utf8))
    }

    @Test(arguments: [
        NSPasteboard.PasteboardType.concealed, .transient, .autoGenerated, .folitaOrigin,
    ])
    func skipsCopiesMarkedAsPrivateOrOwn(marker: NSPasteboard.PasteboardType) {
        #expect(ClipboardCapture.shouldSkip(
            types: [.string, marker],
            sourceBundleID: nil,
            ignoredBundleIDs: []
        ))
    }

    @Test func skipsIgnoredSourceApps() {
        #expect(ClipboardCapture.shouldSkip(
            types: [.string],
            sourceBundleID: "com.example.bank",
            ignoredBundleIDs: ["com.example.bank"]
        ))
        #expect(!ClipboardCapture.shouldSkip(
            types: [.string],
            sourceBundleID: "com.apple.TextEdit",
            ignoredBundleIDs: ["com.example.bank"]
        ))
    }

    @Test func skipsCopiesWithoutSupportedTypes() {
        let webArchive = NSPasteboard.PasteboardType("com.apple.webarchive")
        #expect(ClipboardCapture.shouldSkip(types: [webArchive], sourceBundleID: nil, ignoredBundleIDs: []))
    }

    @Test func mergesItemsKeepingFirstOfEachSupportedType() throws {
        let clip = try #require(ClipboardCapture.makeClip(
            items: [
                [text("first"), ClipContent(type: .init("org.chromium.web-custom-data"), data: Data([1]))],
                [text("second"), ClipContent(type: .rtf, data: Data([2]))],
            ],
            sourceBundleID: "com.microsoft.edgemac"
        ))
        #expect(clip.contents == [text("first"), ClipContent(type: .rtf, data: Data([2]))])
        #expect(clip.sourceBundleID == "com.microsoft.edgemac")
    }

    @Test func keepsEveryFileWhenCopyingMultipleFiles() throws {
        let a = ClipContent(type: .fileURL, data: URL(filePath: "/tmp/a.txt").dataRepresentation)
        let b = ClipContent(type: .fileURL, data: URL(filePath: "/tmp/b.txt").dataRepresentation)
        let clip = try #require(ClipboardCapture.makeClip(
            items: [[a, text("a.txt")], [b, text("b.txt")]],
            sourceBundleID: "com.apple.finder"
        ))
        #expect(clip.contents == [a, text("a.txt"), b])
        #expect(ClipClassification.title(for: clip.contents) == "/tmp/a.txt\n/tmp/b.txt")
    }

    @Test func dropsBlankText() {
        #expect(ClipboardCapture.makeClip(items: [[text("  \n\t ")]], sourceBundleID: nil) == nil)
    }

    @Test func dropsClipsOverSizeLimit() {
        let big = ClipContent(type: .png, data: Data(count: ClipboardCapture.maxClipBytes + 1))
        #expect(ClipboardCapture.makeClip(items: [[big]], sourceBundleID: nil) == nil)

        let fits = ClipContent(type: .png, data: Data(count: ClipboardCapture.maxClipBytes))
        #expect(ClipboardCapture.makeClip(items: [[fits]], sourceBundleID: nil) != nil)
    }

    /// 微信复制图片时 PNG 与未压缩 TIFF 并存，合计超限但单一格式并不大：只保留较小的一种而不是整条丢弃。
    @Test func keepsSmallestImageFormatWhenRedundantFormatsExceedLimit() throws {
        let png = ClipContent(type: .png, data: Data(count: 1_000))
        let tiff = ClipContent(type: .tiff, data: Data(count: ClipboardCapture.maxClipBytes))
        let clip = try #require(ClipboardCapture.makeClip(items: [[tiff, png]], sourceBundleID: nil))
        #expect(clip.contents == [png])
    }

    /// 图片文件的图片数据仍然超限时保留文件地址，历史里至少能看到并打开这个文件。
    @Test func keepsFileReferenceWhenImageDataIsTooLarge() throws {
        let fileURL = ClipContent(type: .fileURL, data: URL(filePath: "/tmp/a.png").dataRepresentation)
        let big = ClipContent(type: .png, data: Data(count: ClipboardCapture.maxClipBytes + 1))
        let clip = try #require(ClipboardCapture.makeClip(items: [[fileURL, big]], sourceBundleID: nil))
        #expect(clip.contents == [fileURL])
    }
}

struct ClipClassificationTests {
    private func text(_ string: String) -> ClipContent {
        ClipContent(type: .string, data: Data(string.utf8))
    }

    @Test(arguments: [
        ("hello world", ClipCategory.text),
        ("https://folita.app/docs?a=1", .link),
        ("  http://example.com  ", .link),
        ("ftp://example.com", .text),
        ("see https://example.com", .text),
        ("someone@example.com", .email),
        ("#1E90FF", .color),
        ("#fff", .color),
        ("rgba(0, 0, 0, 0.5)", .color),
        ("hsl(210, 50%, 40%)", .color),
        ("#12345", .text),
        ("line one\nhttps://example.com", .text),
    ])
    func derivesCategoryFromWholeText(input: String, expected: ClipCategory) {
        #expect(ClipClassification.category(of: [text(input)]) == expected)
    }

    @Test func classifiesByFormats() {
        let fileURL = ClipContent(type: .fileURL, data: URL(filePath: "/tmp/a.txt").dataRepresentation)
        let png = ClipContent(type: .png, data: Data([1]))
        let rtf = ClipContent(type: .rtf, data: Data([1]))

        #expect(ClipClassification.category(of: [fileURL, text("a.txt"), png]) == .file)
        #expect(ClipClassification.category(of: [png]) == .image)
        #expect(ClipClassification.category(of: [text("https://a.com"), rtf]) == .richText)
    }

    @Test func titleUsesFilePathsThenText() {
        let fileURL = ClipContent(type: .fileURL, data: URL(filePath: "/Users/me/Read Me.txt").dataRepresentation)
        #expect(ClipClassification.title(for: [fileURL, text("Read Me.txt")]) == "/Users/me/Read Me.txt")
        #expect(ClipClassification.title(for: [text("  hi  ")]) == "hi")
    }

    @Test func titleFallsBackToRichTextString() throws {
        let attributed = NSAttributedString(string: "Bold words")
        let rtf = try #require(attributed.rtf(from: NSRange(location: 0, length: attributed.length)))
        #expect(ClipClassification.title(for: [ClipContent(type: .rtf, data: rtf)]) == "Bold words")
    }

    @Test func titleRemovesObjectReplacementScalarsAndTruncates() {
        // U+FFFC 后接组合字符时与其构成同一字素簇，必须按 scalar 移除。
        #expect(ClipClassification.sanitizedTitle("你好\u{FFFC}\u{0301}\u{FFFC}世界") == "你好\u{0301}世界")

        let long = String(repeating: "a", count: ClipClassification.maxTitleLength + 50)
        #expect(ClipClassification.sanitizedTitle(long).count == ClipClassification.maxTitleLength)
    }
}
